#!/usr/bin/env node
// Builds the dot-matrix Europe map for variant 03 from Natural Earth land polygons
// (world-atlas land-50m, public domain). The projection comes from config/variants.js,
// so the dots and the cities in engine.html line up exactly.
// Output: assets/europe-dots.js -> window.EUROPE_DOTS = [[x, y, coast], ...]
const fs = require('fs'), path = require('path'), vm = require('vm');
const topojson = require('topojson-client');
(async () => {

const ROOT = path.resolve(__dirname, '..');
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'config/variants.js'), 'utf8'), sandbox);
const cfg = sandbox.window.VARIANTS['03-europe-routes'].europe;
const W = sandbox.window.COMMON.size, H = W;

// Mercator with the same scale as engine.html: x = at.x + (lon - lon0) * pxPerDeg
const k = cfg.pxPerDeg * 180 / Math.PI; // px per radian of longitude
const { geoMercator, geoPath } = await import('d3-geo');
const projection = geoMercator().scale(k).center(cfg.center).translate(cfg.at).clipExtent([[-40, -40], [W + 40, H + 40]]);

const topo = require('world-atlas/land-50m.json');
const land = topojson.feature(topo, topo.objects.land);
// geoPath cuts at the antimeridian and clips to the frame; collect the resulting rings
const rings = []; let cur = null;
geoPath(projection, {
  moveTo(x, y) { cur = [[x, y]]; rings.push(cur); },
  lineTo(x, y) { cur.push([x, y]); },
  closePath() {}, arc() {},
})(land);

function inside(x, y) { // even-odd over all rings (holes handled automatically)
  let c = false;
  for (const r of rings) for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const [xi, yi] = r[i], [xj, yj] = r[j];
    if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) c = !c;
  }
  return c;
}

const st = cfg.dotGrid.step, dots = [];
let row = 0;
for (let y = st / 2; y < H + st; y += st * 0.866, row++) {   // staggered (hex) dot grid
  for (let x = (row % 2 ? st / 2 : 0) + st / 4; x < W + st; x += st) {
    if (!inside(x, y)) continue;
    // coast factor: how many of 6 neighbours are sea (0 = inland, 1 = coastline)
    let sea = 0; for (let a = 0; a < 6; a++) if (!inside(x + st * Math.cos(a * Math.PI / 3), y + st * Math.sin(a * Math.PI / 3))) sea++;
    dots.push([+x.toFixed(1), +y.toFixed(1), +(sea / 6).toFixed(2)]);
  }
}
const out = path.join(ROOT, 'assets/europe-dots.js');
fs.writeFileSync(out, `// generated by src/build-europe.js from Natural Earth land-50m (world-atlas 2.0.2, public domain)\nwindow.EUROPE_DOTS=${JSON.stringify(dots)};\n`);
console.log('dots', dots.length, 'rings', rings.length, '->', path.relative(ROOT, out));
})();
